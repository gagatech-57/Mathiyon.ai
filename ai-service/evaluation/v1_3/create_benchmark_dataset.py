def generate_benchmark_prompts_file():
    prompts_list = []
    category_counts = {}
    id_counter = 1

    # Deterministic order by sorted categories
    sorted_categories = sorted(PROMPT_DATA.keys())

    for cat in sorted_categories:
        items = PROMPT_DATA[cat]
        category_counts[cat] = len(items)
        for item in items:
            p_obj = {
                "id": f"prompt_{id_counter:03d}",
                "category": cat,
                "prompt": item
            }
            prompts_list.append(p_obj)
            id_counter += 1

    output = {
        "metadata": {
            "total_prompts": len(prompts_list),
            "category_counts": category_counts,
            "active_scope": ["general_english", "conversation", "coding", "mathematics", "instruction_following"],
            "excluded_scope": ["tamil", "tanglish"],
            "deterministic_ordering": True
        },
        "prompts": prompts_list
    }

    out_file = os.path.join(EVAL_DIR, "benchmark_prompts.json")
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2, ensure_ascii=False)

    print(f"[OK] Successfully generated {len(prompts_list)} benchmark prompts at {out_file}")
    print(f"[OK] Category Counts: {category_counts}")

if __name__ == "__main__":
    generate_benchmark_prompts_file()
